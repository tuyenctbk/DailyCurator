    fun getDailyCuratorPick(): Artwork {
        // Rotate deterministically by day of year so every day has a featured masterwork
        val dayOfYear = java.util.Calendar.getInstance().get(java.util.Calendar.DAY_OF_YEAR)
        val index = (dayOfYear % allMasterpieces.size)
        return allMasterpieces[index].copy(isDailyPick = true)
    }
